"""
YOLOv8 Training Pipeline for Nigerian Produce Detection & Classification.

Fine-tunes YOLOv8 on Nigerian agricultural produce for:
1. Object detection — localize produce in inspection images
2. Classification — identify crop type (cassava, rice, cocoa, etc.)
3. Defect detection — detect and locate defects (mold, rot, insects, etc.)

Usage:
    # Train produce detector
    python training/train_yolov8.py --task detect --data data/datasets/produce_detect.yaml --epochs 100

    # Train grade classifier
    python training/train_yolov8.py --task classify --data data/datasets/produce_classify/ --epochs 50

    # Train defect detector
    python training/train_yolov8.py --task detect --data data/datasets/defect_detect.yaml --epochs 150

    # Export to ONNX for inference service
    python training/train_yolov8.py --export --model runs/detect/best.pt --format onnx
"""

