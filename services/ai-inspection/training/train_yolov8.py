if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="YOLOv8 Training Pipeline for Nigerian Produce")

    subparsers = parser.add_subparsers(dest="command", help="Command to run")

    # Prepare dataset
    prep = subparsers.add_parser("prepare", help="Prepare dataset from synthetic images")
    prep.add_argument("--source", type=str, default="data/synthetic", help="Source directory with COCO annotations")
    prep.add_argument("--output", type=str, default="data/datasets/produce_detect", help="Output dataset directory")
    prep.add_argument("--task", type=str, choices=["detect", "classify"], default="detect")

    # Train
    train = subparsers.add_parser("train", help="Train YOLOv8 model")
    train.add_argument("--task", type=str, choices=["detect", "classify"], default="detect")
    train.add_argument("--data", type=str, required=True, help="Dataset YAML or directory")
    train.add_argument("--model", type=str, default="m", help="Model size: n/s/m/l/x")
    train.add_argument("--epochs", type=int, default=100)
    train.add_argument("--batch", type=int, default=16)
    train.add_argument("--imgsz", type=int, default=640)
    train.add_argument("--device", type=str, default="")
    train.add_argument("--name", type=str, default="nigerian_produce")

    # Export
    exp = subparsers.add_parser("export", help="Export trained model")
    exp.add_argument("--model", type=str, required=True, help="Path to .pt model")
    exp.add_argument("--format", type=str, default="onnx", choices=["onnx", "torchscript", "tensorrt", "coreml"])
    exp.add_argument("--imgsz", type=int, default=640)

    # Validate
    val = subparsers.add_parser("validate", help="Validate model on test set")
    val.add_argument("--model", type=str, required=True)
    val.add_argument("--data", type=str, required=True)

    args = parser.parse_args()

    if args.command == "prepare":
        if args.task == "detect":
            prepare_dataset_structure(args.source, args.output)
        else:
            prepare_classification_dataset(args.source, args.output)

    elif args.command == "train":
        if args.task == "detect":
            train_detector(
                data_yaml=args.data,
                model_size=args.model,
                epochs=args.epochs,
                batch_size=args.batch,
                image_size=args.imgsz,
                name=args.name,
                device=args.device,
            )
        else:
            train_classifier(
                data_dir=args.data,
                model_size=args.model,
                epochs=args.epochs,
                batch_size=args.batch,
                image_size=args.imgsz,
                name=args.name,
                device=args.device,
            )

    elif args.command == "export":
        export_model(args.model, args.format, args.imgsz)

    elif args.command == "validate":
        validate_model(args.model, args.data)

    else:
        parser.print_help()
